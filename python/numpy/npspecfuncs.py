import numpy as np

zeros = np.zeros((2,3))
ones = np.ones((3,3))
constant = np.full((2,2), 7)
range = np.arange(0,10,2)
linspace = np.linspace(0,1,5)

print("Zero array: ", zeros)
print("Ones array: ", ones)
print("Constant array: ", constant)
print("Range array: ", range)
print("Linspace array: ", linspace)